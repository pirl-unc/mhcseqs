def _row(species: str, prefix: str, scope: str, status: str, evidence: str, notes: str = "") -> dict[str, str]:
    return {
        "species": species,
        "prefix": prefix,
        "scope": scope,
        "status": status,
        "evidence": evidence,
        "notes": notes,
    }


def parse_ipd_taxonomy(html_path: Path) -> list[dict[str, str]]:
    """Extract current official designations from a saved IPD taxonomy page."""
    text = html_path.read_text(encoding="utf-8")
    try:
        block = text.split("var organismList = [", 1)[1].split("];", 1)[0]
    except IndexError as exc:
        raise ValueError(f"Could not find IPD organismList in {html_path}") from exc

    pattern = re.compile(
        r"\{\s*'id':\d+, \"name\": \"(?P<name>[^\"]+)\", "
        r"\"common\": \"[^\"]*\", \"groupid\":\d+, \"group\": "
        r"\"(?P<group>[^\"]+)\",\"alias\": \"(?P<alias>[^\"]+)\","
        r"\"taxon\":(?P<taxon>\d+)\}"
    )
    result = []
    for match in pattern.finditer(block):
        values = match.groupdict()
        species = html.unescape(values["name"])
        raw_designation = html.unescape(values["alias"])
        prefixes = list(dict.fromkeys(re.findall(r"[A-Za-z][A-Za-z0-9-]*", raw_designation)))
        for prefix in prefixes:
            result.append(
                _row(
                    species,
                    prefix,
                    "exact",
                    "ipd_current",
                    IPD_TAXONOMY_URL,
                    f"IPD group={values['group']}; taxon={values['taxon']}; designation={raw_designation}",
                )
            )
    if len({row["species"] for row in result}) != 125:
        raise ValueError("Expected the current IPD taxonomy snapshot to contain 125 organisms")
    return result


def load_legacy_source_aliases(audit_path: Path) -> list[dict[str, str]]:
    """Load prefix spellings that occur in external source labels."""
    result = []
    with audit_path.open(encoding="utf-8") as handle:
        for audit_row in csv.DictReader(handle):
            if audit_row["status"] not in {
                "external_registry_or_literature",
                "external_uniprot_label",
            }:
                continue
            prefix = audit_row["legacy_prefix"]
            if prefix in GENERIC_SOURCE_LABELS:
                continue
            status = "external_database" if audit_row["status"] == "external_uniprot_label" else "formal_system"
            accessions = audit_row["example_accessions"]
            notes = (
                "attested in the retained source label for " + accessions if accessions else "source established by the cited registry or literature"
            )
            result.append(
                _row(
                    audit_row["species"],
                    prefix,
                    "exact",
                    status,
                    audit_row["evidence"],
                    notes,
                )
            )
    return result


def build_registry(audit_path: Path, ipd_html_path: Path) -> list[dict[str, str]]:
    """Combine, de-duplicate, and deterministically order registry rows."""
    rows = parse_ipd_taxonomy(ipd_html_path)
    rows.extend(load_legacy_source_aliases(audit_path))
    rows.extend(_row(species, prefix, scope, "formal_system", source) for species, prefix, scope, source in SYSTEM_PREFIXES)
    rows.extend(_row(species, prefix, scope, "literature_historical", source) for species, prefix, scope, source in HISTORICAL_PREFIXES)
    rows.extend(
        _row(species, prefix, scope, "external_database", source, notes) for species, prefix, scope, source, notes in ADDITIONAL_DATABASE_PREFIXES
    )

    priority = {
        "ipd_current": 0,
        "formal_system": 1,
        "literature_historical": 2,
        "external_database": 3,
    }
    selected: dict[tuple[str, str, str], dict[str, str]] = {}
    for row in rows:
        key = (row["species"].casefold(), row["prefix"].casefold(), row["scope"])
        previous = selected.get(key)
        if previous is None or priority[row["status"]] < priority[previous["status"]]:
            selected[key] = row
    return sorted(
        selected.values(),
        key=lambda row: (row["species"].casefold(), priority[row["status"]], row["prefix"].casefold()),
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--audit", type=Path, default=DEFAULT_AUDIT)
    parser.add_argument("--ipd-html", type=Path, required=True)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()

    rows = build_registry(args.audit, args.ipd_html)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=FIELDS, lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
    print(f"Wrote {len(rows)} source-attested aliases to {args.output}")


if __name__ == "__main__":
    main()
