#!/usr/bin/env python3
"""Build the source-attested MHC prefix registry shipped by mhcseqs.

The registry combines three kinds of evidence:

* current official species designations from the IPD-MHC taxonomy page;
* prefixes present in the retained UniProt source labels for the legacy
  diverse-MHC corpus; and
* explicitly curated historical nomenclature from primary papers and
  nomenclature reports.

Generated 2+2/4+4/5+5 spellings are deliberately not accepted merely because
they can be derived from a scientific name.
"""

